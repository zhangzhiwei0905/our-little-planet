export function isStickerName(v: string): v is StickerName {
  return v in SHAPES;
}

export function Sticker({
  name,
  className,
}: {
  name: StickerName;
  className?: string;
}) {
  const s = SHAPES[name];
  // cn 是纯拼接：调用方带 size-* 时不能再拼默认的 size-10，否则两个类同时生效、
  // 按 CSS 顺序 size-10 会压掉更小的尺寸（图标选择器里就是这样撑出圆圈的）
  const hasSize = className ? /(?:^|\s)size-(?:[0-9]|full|\[)/.test(className) : false;
  return (
    <svg viewBox={s.vb} aria-hidden className={cn(hasSize ? null : "size-10", className)} fill="currentColor">
      {s.el}
    </svg>
  );
}
